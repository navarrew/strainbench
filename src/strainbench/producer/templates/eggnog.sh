#!/usr/bin/env bash
# ──────────────────────────────────────────────────────────────────────────────
# eggNOG-mapper annotation of strainbench cluster representatives.
#
# Prerequisites (once per machine):
#   conda create -n emapper -c bioconda eggnog-mapper
#   conda activate emapper
#   download_eggnog_data.py --data_dir $HOME/databases/eggnog-v6
#
# Running:
#   conda activate emapper
#   bash eggnog.sh
#
# Customize by exporting env vars BEFORE running (or editing below):
#   EMAPPER_DATA_DIR    path to eggnog database (default: ~/databases/eggnog-v6)
#   EMAPPER_THREADS     number of CPU threads                 (default: 8)
#   EMAPPER_MODE        alignment mode                        (default: diamond)
# ──────────────────────────────────────────────────────────────────────────────
set -euo pipefail

EMAPPER_DATA_DIR="${EMAPPER_DATA_DIR:-$HOME/databases/eggnog-v6}"
EMAPPER_THREADS="${EMAPPER_THREADS:-8}"
EMAPPER_MODE="${EMAPPER_MODE:-diamond}"

# Auto-generated by `strainbench annotate-prep`:
REPS_FASTA="${STRAINBENCH_REPS:-reps.faa}"
OUTPUT_DIR="emapper_out"
OUTPUT_PREFIX="emapper"

# Pre-flight checks
if ! command -v emapper.py >/dev/null 2>&1; then
    echo "ERROR: emapper.py not found on PATH." >&2
    echo "Did you 'conda activate emapper'?" >&2
    exit 2
fi
if [ ! -d "$EMAPPER_DATA_DIR" ]; then
    echo "ERROR: eggNOG database directory not found: $EMAPPER_DATA_DIR" >&2
    echo "Download it once with:" >&2
    echo "  download_eggnog_data.py --data_dir $EMAPPER_DATA_DIR" >&2
    echo "or export EMAPPER_DATA_DIR to point at an existing install." >&2
    exit 3
fi
if [ ! -s "$REPS_FASTA" ]; then
    echo "ERROR: $REPS_FASTA not found. Run 'strainbench export-reps' first." >&2
    exit 4
fi

mkdir -p "$OUTPUT_DIR"
echo "Running eggNOG-mapper..."
echo "  input:      $REPS_FASTA"
echo "  data dir:   $EMAPPER_DATA_DIR"
echo "  mode:       $EMAPPER_MODE"
echo "  threads:    $EMAPPER_THREADS"
echo "  output:     $OUTPUT_DIR/$OUTPUT_PREFIX.emapper.annotations"
echo

emapper.py \
    -i "$REPS_FASTA" \
    -o "$OUTPUT_PREFIX" \
    --output_dir "$OUTPUT_DIR" \
    --data_dir "$EMAPPER_DATA_DIR" \
    -m "$EMAPPER_MODE" \
    --cpu "$EMAPPER_THREADS" \
    --override

echo
echo "Done. Import with:"
echo "  strainbench import-annotation --workdir ."
